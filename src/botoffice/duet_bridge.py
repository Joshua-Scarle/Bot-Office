def _get_api(path: str, environ: dict[str, str] | None, data_dir: Path | None) -> dict[str, Any]:
    from . import grok_bridge
    env = dict(os.environ) if environ is None else environ
    request = urllib.request.Request(grok_bridge._api_url(env) + path, method="GET", headers={
        "Authorization": f"Bearer {grok_bridge._api_token(env, data_dir)}"})
    try:
        with grok_bridge._NO_REDIRECTS.open(request, timeout=30) as response:
            return json.loads(response.read() or b"{}")
    except urllib.error.HTTPError as exc:
        try:
            detail = json.loads(exc.read() or b"{}").get("detail")
        except ValueError:
            detail = None
        raise DeskError(detail if isinstance(detail, str) else f"Bot-Office API HTTP {exc.code}") from exc
    except (urllib.error.URLError, OSError, ValueError) as exc:
        raise DeskError("Bot-Office API unreachable") from exc


def desk_duet(argv: list[str], *, stdin=None, data_dir: Path | None = None,
              environ: dict[str, str] | None = None) -> int:
    if not argv or argv[0] in {"-h", "--help"}:
        print(USAGE_DUET)
        return 0
    command, rest = argv[0], argv[1:]
    env = environ if environ is not None else os.environ
    if command == "install-config":
        if env.get("BOT_OFFICE_AGENT_TOKEN") or env.get("BOT_OFFICE_JOB_ID"):
            raise DeskError("install-config is for the operator; it cannot run inside a bot turn")
        directory = data_dir or Settings.from_env().control_dir
        print(f"wrote {install_config((stdin or sys.stdin).read(), directory)} (mode 0600)")
        return 0
    if command == "status":
        print(json.dumps(_get_api("/v1/bridge/duet/status", environ, data_dir), indent=2))
        return 0
    if command != "send":
        raise DeskError(USAGE_DUET)
    from . import grok_bridge
    parser = argparse.ArgumentParser(prog="desk duet send", usage=USAGE_DUET)
    parser.add_argument("--text", required=True)
    parser.add_argument("--to", default="main")
    parser.add_argument("--kind", default="fyi")
    parser.add_argument("--thread")
    parser.add_argument("--reply-to", dest="reply_to")
    parser.add_argument("--id", dest="msg_id")
    parser.add_argument("--from", dest="from_bot")
    args = parser.parse_args(rest)
    body: dict[str, Any] = {"text": args.text, "to": args.to, "kind": args.kind, "thread": args.thread,
                            "reply_to": args.reply_to}
    if args.from_bot:
        body["from"] = args.from_bot
    if args.msg_id:
        body["id"] = args.msg_id
    data = grok_bridge.call_api("/v1/bridge/duet/send", body, environ=environ, data_dir=data_dir)
    print(f"sent {data.get('id')} {data.get('url') or ''}".strip())
    return 0
