"""Claude Duet bridge: a pull request on a private repository is the mailbox (docs/DUET-BRIDGE.md).

- Inbound: a controller thread polls the PR's issue comments with conditional requests (a 304 costs
  nothing). An unedited comment from an allowed GitHub account (pinned by numeric id, type User or Bot)
  whose first line is ``[Duet -> Bot Office] ...`` is recorded as pending, then delivered to a bot as
  untrusted data: steered into its running turn, else a new turn. A failed delivery stays pending and is
  retried.
- Outbound: ``DuetBridge.send`` (``POST /v1/bridge/duet/send``) posts ``[Bot Office -> Duet] ...`` as a pull
  request review (event COMMENT) with the controller's own GitHub token. Every post (including the bridge's
  own error notices) goes through one path: repository check (private, same id as first seen), rate and
  thread limits reserved in SQLite before the HTTP call, and a secret scan of the final serialized body.
  Only review events wake the subscribed Duet session; plain conversation comments do not, which is also
  why Duet's own sends (conversation comments) do not wake Duet and are read by the poller instead.

Stdlib only; HTTP goes through an injectable transport so tests never touch the network. The GitHub
token comes from rules.github_token (the controller's own file) and is never logged here. It is the same token
bot runs get for ticketed git and gh calls (api /v1/agent/github-token), so it must stay limited to the mailbox
repository (docs/DUET-BRIDGE.md, "GitHub token").
"""
