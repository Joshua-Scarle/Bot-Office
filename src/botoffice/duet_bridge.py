"""Claude Duet bridge: a pull request on a private repository is the mailbox (docs/DUET-BRIDGE.md).

- Inbound: a controller thread polls the PR's issue comments with conditional requests (a 304 costs
  nothing). A comment from an allowed GitHub login whose first line is ``[Duet -> Bot Office] ...`` is
  delivered to a bot as untrusted data: steered into its running turn, else a new turn.
- Outbound: ``DuetBridge.send`` (``POST /v1/bridge/duet/send``) posts ``[Bot Office -> Duet] ...`` as a pull
  request review (event COMMENT) with the controller's own GitHub token, after secret, denylist and rate
  checks. Only review events wake the subscribed Duet session; plain conversation comments do not, which is
  also why Duet's own sends (conversation comments) do not wake Duet and are read by the poller instead.

Stdlib only; HTTP goes through an injectable transport so tests never touch the network. The GitHub
token comes from rules.github_token (the controller's own file) and is never logged or handed out.
"""
