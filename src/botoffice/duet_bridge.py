from . import rules, watchers
from .config import Settings, first_env
from .desk import DeskError

log = logging.getLogger("botoffice.duet")

CONFIG_NAME = "duet_mailbox.json"
GITHUB_API = "https://api.github.com"
IN_KINDS = ("task", "question", "result", "fyi")
OUT_KINDS = ("task", "question", "result", "fyi", "blocker", "error")
MAX_TEXT = 60_000
DEFAULT_INTERVAL = 4
MIN_INTERVAL, MAX_INTERVAL = 2, 60
PER_BOT_SECONDS = 3
PER_MINUTE = 40
PER_DAY = 1000
THREAD_CAP = 30
MAX_BACKOFF = 60
MAX_RATE_WAIT = 900
SENDER = "Claude Duet"

# a footer some tools append to a comment: a "---" line, then a line starting "_Generated by"
_FOOTER = re.compile(r"(?:^|\n)-{3}[ \t]*\r?\n_Generated by.*\Z", re.S)
_INBOUND_PREFIX = re.compile(r"^\[Duet\s*(?:→|->)\s*Bot Office\]")
_SAFE = re.compile(r"[^A-Za-z0-9_.:@/-]")
_REPO = re.compile(r"^[A-Za-z0-9_.-]{1,100}/[A-Za-z0-9_.-]{1,100}$")
_LOGIN = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,38})$")
_SECRETS = (
    watchers._REDACT[0], watchers._REDACT[1],
    re.compile(r"\bsk-[A-Za-z0-9_-]{16,}"),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),
    re.compile(r"-----BEGIN"),
    re.compile(r"\bxox[abprs]-[A-Za-z0-9-]{10,}"),
    re.compile(r"\bAIza[0-9A-Za-z_-]{35}\b"),
)

USAGE_DUET = (
    "usage: desk duet send --text TEXT [--to main] [--kind task|question|result|fyi|blocker] [--thread ID]"
    " [--reply-to ID] [--from NAME]\n"
    "       desk duet status\n"
    "       desk duet install-config   # reads the mailbox JSON from stdin (operator only)"
)


class DuetError(DeskError):
    """*status* is the HTTP status the API answers with."""

    def __init__(self, message: str, status: int = 400):
        super().__init__(message)
        self.status = status


# --- config ---


@dataclass(frozen=True)
class DuetConfig:
    repo: str
    pr: int
    default_bot: str
    interval: int = DEFAULT_INTERVAL
    allowed_authors: tuple[str, ...] = ()
    enabled: bool = True


def config_path(control_dir: Path) -> Path:
    return control_dir / CONFIG_NAME


def parse_config(data: Any) -> DuetConfig:
    if not isinstance(data, dict):
        raise DuetError("duet config must be a JSON object")
    repo = str(data.get("repo") or "").strip()
    if not _REPO.match(repo):
        raise DuetError("repo must look like owner/name")
    pr = data.get("pr")
    if isinstance(pr, bool) or not isinstance(pr, int) or pr < 1:
        raise DuetError("pr must be a positive integer")
    default_bot = str(data.get("default_bot") or "").strip()
    if not default_bot:
        raise DuetError("default_bot is required")
    interval = data.get("interval", DEFAULT_INTERVAL)
    if isinstance(interval, bool) or not isinstance(interval, (int, float)):
        raise DuetError("interval must be a number of seconds")
    interval = int(min(MAX_INTERVAL, max(MIN_INTERVAL, interval)))
    authors = data.get("allowed_authors") or []
    if not isinstance(authors, list) or not all(isinstance(a, str) and _LOGIN.match(a.strip()) for a in authors):
        raise DuetError("allowed_authors must be a list of GitHub logins")
    enabled = data.get("enabled", True)
    if not isinstance(enabled, bool):
        raise DuetError("enabled must be true or false")
    return DuetConfig(repo, pr, default_bot, interval, tuple(a.strip() for a in authors), enabled)


def load_config(control_dir: Path) -> DuetConfig | None:
    """None when there is no file. A file with group or world bits, a symlink or bad JSON is refused."""
    path = config_path(control_dir)
    try:
        if path.is_symlink():
            raise DuetError("duet config must not be a symlink")
        mode = path.stat().st_mode
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise DuetError("duet config is unreadable") from exc
    if mode & 0o077:
        raise DuetError("duet config is readable by others; run chmod 600 on it")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise DuetError("duet config is unreadable or not JSON") from exc
    return parse_config(data)


def install_config(raw: str, control_dir: Path) -> Path:
    text = raw.strip()
    if not text:
        raise DuetError("expected the mailbox JSON on stdin")
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise DuetError("stdin must be JSON") from exc
    config = parse_config(data)
    out = {"repo": config.repo, "pr": config.pr, "default_bot": config.default_bot, "interval": config.interval,
           "allowed_authors": list(config.allowed_authors), "enabled": config.enabled}
    path = config_path(control_dir)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    tmp = path.with_name(f".{path.name}.tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as stream:
        stream.write(json.dumps(out, indent=2) + "\n")
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)
    return path


# --- HTTP ---

Transport = Callable[[str, str, dict[str, str], bytes | None], tuple[int, dict[str, str], bytes]]


class _NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):  # noqa: ANN001
        return None


_OPENER = urllib.request.build_opener(_NoRedirect())


def default_transport(method: str, url: str, headers: dict[str, str], body: bytes | None
                      ) -> tuple[int, dict[str, str], bytes]:
    """(status, lower-cased response headers, body). Network failures raise OSError (URLError is one)."""
    request = urllib.request.Request(url, data=body, method=method, headers=headers)
    try:
        with _OPENER.open(request, timeout=20) as response:
            return response.getcode(), {k.lower(): v for k, v in response.headers.items()}, response.read(8_000_000)
    except urllib.error.HTTPError as exc:
        return exc.code, {k.lower(): v for k, v in exc.headers.items()}, exc.read(1_000_000)


def _next_link(header: str | None) -> str | None:
    for part in (header or "").split(","):
        match = re.match(r'\s*<([^>]+)>\s*;\s*rel="next"', part)
        if match:
            return match.group(1)
    return None


def _clean(value: str, limit: int = 64) -> str:
    return _SAFE.sub("_", value)[:limit]


def parse_inbound(body: str) -> tuple[dict[str, str], str] | None:
    """(header fields, text) for a Duet to Bot Office comment, else None."""
    lines = _FOOTER.sub("", (body or "").lstrip("\ufeff")).split("\n", 1)
    first = lines[0].rstrip("\r").strip()
    match = _INBOUND_PREFIX.match(first)
    if not match:
        return None
    fields: dict[str, str] = {}
    for token in first[match.end():].split():
        key, sep, value = token.partition("=")
        if sep and key.lower() in ("id", "to", "thread", "kind") and value:
            fields[key.lower()] = value
    return fields, (lines[1] if len(lines) > 1 else "").strip()[:MAX_TEXT]


@dataclass
class _Status:
    last_poll_at: str | None = None
    last_http_status: int | None = None
    polls: int = 0
    not_modified: int = 0
    last_error: str | None = None
    errors: int = 0


@dataclass
class DuetBridge:
    store: Any  # JobStore
    settings: Settings
    turns: Any = None  # Turns (post_message for an idle bot)
    steer: Callable[[Any, str], bool] | None = None  # (bot, text) -> True when attached to a running/queued turn
    transport: Transport = default_transport
    clock: Callable[[], datetime] = lambda: datetime.now(UTC)
    status: _Status = field(default_factory=_Status)

    def __post_init__(self) -> None:
        self._login: str | None = None
        self._send_lock = threading.Lock()
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self._cfg_cache: tuple[tuple[int, int], DuetConfig | None] | None = None
        self._api = first_env("BOT_OFFICE_GITHUB_API") or GITHUB_API

    # -- plumbing --

    def _db(self):
        return closing(self.store._connect())

    def _iso(self, moment: datetime | None = None) -> str:
        return (moment or self.clock()).astimezone(UTC).isoformat()

    def config(self) -> DuetConfig | None:
        path = config_path(self.settings.control_dir)
        try:
            stat = path.stat()
            key = (stat.st_mtime_ns, stat.st_size | (stat.st_mode & 0o077) << 40)
        except OSError:
            self._cfg_cache = None
            return None
        if self._cfg_cache and self._cfg_cache[0] == key:
            return self._cfg_cache[1]
        config = load_config(self.settings.control_dir)  # raises DuetError for a loose or bad file
        self._cfg_cache = (key, config)
        return config

    def _headers(self, token: str, extra: dict[str, str] | None = None) -> dict[str, str]:
        headers = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                   "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "bot-office-duet"}
        headers.update(extra or {})
        return headers

    def _token(self) -> str:
        token = rules.github_token(self.settings)
        if not token:
            raise DuetError("no usable GitHub token (control dir github-token, mode 600)", 503)
        return token

    def _meta(self, key: str) -> str | None:
        return self.store.get_meta(key)

    def allowed_authors(self, config: DuetConfig, token: str) -> set[str]:
        if config.allowed_authors:
            return {a.lower() for a in config.allowed_authors}
        if self._login is None:
            status, _, body = self.transport("GET", f"{self._api}/user", self._headers(token), None)
            if status != 200:
                raise DuetError(f"GET /user answered HTTP {status}", 502)
            login = json.loads(body or b"{}").get("login")
            if not isinstance(login, str) or not login:
                raise DuetError("GET /user returned no login", 502)
            self._login = login
        return {self._login.lower()}

    # -- inbound --

    def poll_once(self) -> float | None:
        """One poll. Returns seconds to wait before the next one when the server asked for more than the
        interval (rate limit), else None. Raises OSError/DuetError on failure (the loop backs off)."""
        config = self.config()
        if config is None or not config.enabled:
            return None
        token = self._token()
        allowed = self.allowed_authors(config, token)
        cursor = self._meta("duet_cursor")
        if not cursor:
            cursor = self.clock().astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
            self.store.set_meta("duet_cursor", cursor)  # first start: never replay history
        since = quote(cursor, safe="")
        url = f"{self._api}/repos/{config.repo}/issues/{config.pr}/comments?per_page=100&since={since}"
        extra = {}
        etag_row = self._meta("duet_etag")
        if etag_row:
            try:
                saved = json.loads(etag_row)
            except ValueError:
                saved = {}
            if saved.get("url") == url and saved.get("etag"):
                extra["If-None-Match"] = saved["etag"]
        self.status.polls += 1
        self.status.last_poll_at = self._iso()
        status, headers, body = self.transport("GET", url, self._headers(token, extra), None)
        self.status.last_http_status = status
        if status == 304:
            self.status.not_modified += 1
            self.status.last_error = None
            return None
        wait = self._rate_wait(status, headers)
        if wait is not None:
            raise _RateLimited(wait)
        if status != 200:
            raise DuetError(f"GitHub comments answered HTTP {status}", 502)
        etag = headers.get("etag")
        newest = cursor
        pages = 0
        while True:
            comments = json.loads(body or b"[]")
            if not isinstance(comments, list):
                raise DuetError("GitHub comments answer was not a list", 502)
            for comment in sorted((c for c in comments if isinstance(c, dict)), key=lambda c: c.get("id") or 0):
                stamp = str(comment.get("updated_at") or "")
                if stamp > newest:
                    newest = stamp
                self._handle_comment(config, token, allowed, comment)
            nxt = _next_link(headers.get("link"))
            pages += 1
            if not nxt or pages >= 50:
                break
            if not nxt.startswith(self._api + "/"):
                raise DuetError("refusing a pagination link outside the GitHub API", 502)
            status, headers, body = self.transport("GET", nxt, self._headers(token), None)
            wait = self._rate_wait(status, headers)
            if wait is not None:
                raise _RateLimited(wait)
            if status != 200:
                raise DuetError(f"GitHub comments page answered HTTP {status}", 502)
        if newest != cursor:
            self.store.set_meta("duet_cursor", newest)
            # the cursor moved, so the URL changed: the old etag no longer applies
            self.store.delete_meta("duet_etag")
        elif etag:
            self.store.set_meta("duet_etag", json.dumps({"url": url, "etag": etag}))
        self.status.last_error = None
        return None

    @staticmethod
    def _rate_wait(status: int, headers: dict[str, str]) -> float | None:
        if status not in (403, 429):
            return None
        retry = headers.get("retry-after")
        if retry and retry.strip().isdigit():
            return min(MAX_RATE_WAIT, float(retry))
        if status == 429 or headers.get("x-ratelimit-remaining") == "0":
            reset = headers.get("x-ratelimit-reset")
            if reset and reset.strip().isdigit():
                return min(MAX_RATE_WAIT, max(1.0, float(reset) - datetime.now(UTC).timestamp()))
            return 60.0
        return None

    def _handle_comment(self, config: DuetConfig, token: str, allowed: set[str], comment: dict) -> None:
        try:
            comment_id = int(comment["id"])
        except (KeyError, TypeError, ValueError):
            return
        user = comment.get("user") or {}
        login = str(user.get("login") or "").lower() if isinstance(user, dict) else ""
        parsed = parse_inbound(str(comment.get("body") or ""))
        if parsed is None or login not in allowed:
            return
        fields, text = parsed
        msg_id = _clean(fields.get("id", "")) or f"GH-{comment_id}"
        thread = _clean(fields.get("thread", ""))
        kind = fields.get("kind", "fyi").lower()
        if kind not in IN_KINDS:
            kind = "fyi"
        stamp = self._iso()
        with self._db() as db:
            cur = db.execute(
                "INSERT OR IGNORE INTO duet_messages (comment_id,direction,msg_id,thread,kind,gh_created_at,seen_at) "
                "VALUES (?,?,?,?,?,?,?)",
                (comment_id, "in", msg_id, thread, kind, str(comment.get("created_at") or ""), stamp))
            if cur.rowcount == 0:
                return  # already seen: delivered once only
        target = fields.get("to", "")
        bot = (self.store.find_bot(target) if target and target.lower() != "default" else None) \
            or self.store.find_bot(config.default_bot)
        if bot is None:
            self._finish(comment_id, error="no such bot")
            self._publish(config, token, sender="bot-office", to="main", kind="error", thread=thread,
                          reply_to=msg_id, text=f"Message {msg_id} was not delivered: bot "
                          f"'{_clean(target or config.default_bot)}' was not found, and there is no usable default bot.")
            return
        prompt = self.wrap_inbound(msg_id, thread, kind, text)
        try:
            mode, job_id = self._deliver(bot, prompt)
        except Exception as exc:  # noqa: BLE001 - recorded, never raised: one bad message must not stall the box
            log.warning("duet delivery of %s failed: %s", msg_id, type(exc).__name__)
            self._finish(comment_id, error=f"delivery failed: {type(exc).__name__}: {str(exc)[:200]}")
            return
        self._finish(comment_id, bot_id=str(bot.id), job_id=job_id, mode=mode, delivered_at=self._iso())
        try:
            self.react(config, token, comment_id)
        except Exception as exc:  # noqa: BLE001
            log.warning("duet reaction failed: %s", type(exc).__name__)

    @staticmethod
    def wrap_inbound(msg_id: str, thread: str, kind: str, text: str) -> str:
        reply = f'desk duet send --reply-to {msg_id}' + (f" --thread {thread}" if thread else "") + ' --text "..."'
        head = f"[Message from {SENDER} via the Duet mailbox: id={msg_id}" + \
               (f" thread={thread}" if thread else "") + f" kind={kind}]"
        return "\n".join((head, rules.UNTRUSTED_RULE, rules.untrusted("claude-duet", text),
                          f"To reply: {reply}"))

    def _deliver(self, bot: Any, prompt: str) -> tuple[str, str | None]:
        if self.steer is not None and self.steer(bot, prompt):
            return "steer", None
        if self.turns is None:
            raise DuetError("no turn queue", 503)
        _message, job = self.turns.post_message(bot, prompt, source="inbox", sender=SENDER)
        return "turn", str(job.id)

    def _finish(self, comment_id: int, **values: Any) -> None:
        if not values:
            return
        cols = ", ".join(f"{k}=?" for k in values)
        with self._db() as db:
            db.execute(f"UPDATE duet_messages SET {cols} WHERE comment_id=?", (*values.values(), comment_id))

    def react(self, config: DuetConfig, token: str, comment_id: int) -> None:
        url = f"{self._api}/repos/{config.repo}/issues/comments/{comment_id}/reactions"
        status, _, _ = self.transport("POST", url, self._headers(token, {"Content-Type": "application/json"}),
                                      json.dumps({"content": "eyes"}).encode())
        if status not in (200, 201):
            raise DuetError(f"reaction answered HTTP {status}", 502)

    # -- outbound --

    @staticmethod
    def check_text(text: str) -> None:
        """Refuse a secret-looking or denylisted text. Never echoes the matched value."""
        if any(pattern.search(text) for pattern in _SECRETS):
            raise DuetError("message refused: it looks like it contains a secret or token")
        path = Path(first_env("BO_PUSH_DENYLIST") or "~/.config/bot-office/push-denylist.txt").expanduser()
        try:
            literals = [line.strip().lower() for line in path.read_text(encoding="utf-8").splitlines()]
        except (OSError, UnicodeDecodeError):
            return
        lowered = text.lower()
        if any(item and not item.startswith("#") and item in lowered for item in literals):
            raise DuetError("message refused: it contains a value on the push denylist")

    def send(self, *, text: str, sender: str, to: str = "main", kind: str = "fyi", thread: str | None = None,
             reply_to: str | None = None) -> dict[str, Any]:
        text = (text or "").strip()
        if not text:
            raise DuetError("text must not be empty")
        if len(text) > MAX_TEXT:
            raise DuetError(f"text is over {MAX_TEXT} characters")
        kind = (kind or "fyi").strip().lower()
        if kind not in OUT_KINDS or kind == "error":
            raise DuetError(f"kind must be one of {', '.join(k for k in OUT_KINDS if k != 'error')}")
        sender = (sender or "").strip() or "agentdesk"
        to = _clean((to or "").strip() or "main")
        thread = _clean((thread or "").strip())
        reply_to = _clean((reply_to or "").strip())
        self.check_text(text)
        config = self.config()
        if config is None or not config.enabled:
            raise DuetError("the Duet bridge is not configured or is disabled", 503)
        token = self._token()
        with self._send_lock:
            if reply_to and not thread:
                with self._db() as db:
                    row = db.execute("SELECT thread FROM duet_messages WHERE msg_id=? AND thread!='' LIMIT 1",
                                     (reply_to,)).fetchone()
                thread = row["thread"] if row else ""
            self._check_limits(sender, thread)
            return self._publish(config, token, sender=sender, to=to, kind=kind, thread=thread,
                                 reply_to=reply_to, text=text)

    def _check_limits(self, sender: str, thread: str) -> None:
        moment = self.clock()
        with self._db() as db:
            def count(since: datetime, bot: str | None = None) -> int:
                sql = "SELECT COUNT(*) FROM duet_messages WHERE direction='out' AND seen_at>=?"
                args: list[Any] = [self._iso(since)]
                if bot is not None:
                    sql += " AND bot_id=?"
                    args.append(bot)
                return int(db.execute(sql, args).fetchone()[0])
            if count(moment - timedelta(seconds=PER_BOT_SECONDS), sender):
                raise DuetError(f"slow down: one send per {PER_BOT_SECONDS} s per bot", 429)
            if count(moment - timedelta(seconds=60)) >= PER_MINUTE:
                raise DuetError(f"slow down: at most {PER_MINUTE} sends a minute", 429)
            if count(moment - timedelta(days=1)) >= PER_DAY:
                raise DuetError(f"daily limit of {PER_DAY} sends reached", 429)
            if thread:
                used = db.execute("SELECT COUNT(*) FROM duet_messages WHERE thread=?", (thread,)).fetchone()[0]
                if used >= THREAD_CAP:
                    raise DuetError(f"thread cap of {THREAD_CAP} messages reached; start a new thread", 429)

    def _publish(self, config: DuetConfig, token: str, *, sender: str, to: str, kind: str, thread: str,
                 reply_to: str, text: str) -> dict[str, Any]:
        msg_id = f"BO-{uuid.uuid4().hex[:8]}"
        parts = [("id", msg_id), ("from", _clean(sender, 80) or "agentdesk"), ("to", to), ("thread", thread),
                 ("reply_to", reply_to), ("kind", kind)]
        header = "[Bot Office → Duet] " + " ".join(f"{k}={v}" for k, v in parts if v)
        url = f"{self._api}/repos/{config.repo}/pulls/{config.pr}/reviews"
        status, _, body = self.transport("POST", url, self._headers(token, {"Content-Type": "application/json"}),
                                         json.dumps({"event": "COMMENT", "body": f"{header}\n\n{text}"}).encode())
        if status not in (200, 201):
            raise DuetError(f"GitHub refused the review (HTTP {status})", 502)
        data = json.loads(body or b"{}")
        review_id = int(data["id"])
        stamp = self._iso()
        with self._db() as db:
            # review ids are a different id space from comment ids: an outbound row is keyed by -review_id
            db.execute("INSERT OR REPLACE INTO duet_messages (comment_id,direction,msg_id,thread,kind,bot_id,"
                       "gh_created_at,seen_at,delivered_at,mode,review_id) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                       (-review_id, "out", msg_id, thread, kind, sender, str(data.get("submitted_at") or stamp),
                        stamp, stamp, "review", review_id))
        return {"id": msg_id, "review_id": review_id, "url": str(data.get("html_url") or "")}

    # -- status --

    def report(self) -> dict[str, Any]:
        try:
            config = self.config()
            problem = None
        except DuetError as exc:
            config, problem = None, str(exc)
        with self._db() as db:
            counts = {row[0]: row[1] for row in db.execute(
                "SELECT direction, COUNT(*) FROM duet_messages GROUP BY direction")}
            rows = db.execute("SELECT gh_created_at, delivered_at FROM duet_messages WHERE direction='in' "
                              "AND delivered_at IS NOT NULL ORDER BY seen_at DESC LIMIT 20").fetchall()
            failed = db.execute("SELECT COUNT(*) FROM duet_messages WHERE direction='in' AND error IS NOT NULL"
                                ).fetchone()[0]
        latencies = []
        for row in rows:
            try:
                created = datetime.fromisoformat(str(row["gh_created_at"]).replace("Z", "+00:00"))
                delivered = datetime.fromisoformat(str(row["delivered_at"]))
                latencies.append(round((delivered - created).total_seconds(), 1))
            except ValueError:
                continue
        s = self.status
        return {"enabled": bool(config and config.enabled), "configured": config is not None,
                "config_problem": problem, "running": bool(self._thread and self._thread.is_alive()),
                "repo": config.repo if config else None, "pr": config.pr if config else None,
                "last_poll_at": s.last_poll_at, "last_http_status": s.last_http_status, "polls": s.polls,
                "not_modified": s.not_modified, "last_error": s.last_error,
                "inbound": counts.get("in", 0), "inbound_failed": failed, "outbound": counts.get("out", 0),
                "latencies_seconds": latencies}

    # -- the loop --

    def start(self) -> None:
        if self._thread and self._thread.is_alive():
            return
        self._stop.clear()
        self._thread = threading.Thread(target=self._run, name="botoffice-duet", daemon=True)
        self._thread.start()

    def stop(self) -> None:
        self._stop.set()
        if self._thread:
            self._thread.join(timeout=5)

    def _run(self) -> None:
        failures = 0
        while not self._stop.is_set():
            delay: float = DEFAULT_INTERVAL
            try:
                config = self.config()
                delay = float(config.interval) if config else 10.0
                wait = self.poll_once()
                failures = 0
                if wait:
                    delay = wait
            except _RateLimited as exc:
                delay = exc.seconds
                self.status.last_error = f"rate limited; waiting {int(delay)} s"
            except (OSError, DuetError, ValueError, KeyError) as exc:
                failures += 1
                delay = float(min(MAX_BACKOFF, 2 ** min(failures, 6)))
                self.status.errors += 1
                self.status.last_error = f"{type(exc).__name__}: {str(exc)[:200]}"
                log.warning("duet poll failed (%s), retry in %.0f s", type(exc).__name__, delay)
            except Exception as exc:  # noqa: BLE001 - the loop must survive
                failures += 1
                delay = float(min(MAX_BACKOFF, 2 ** min(failures, 6)))
                self.status.last_error = f"{type(exc).__name__}"
                log.exception("duet poll crashed")
            self._stop.wait(delay)


class _RateLimited(Exception):
    def __init__(self, seconds: float):
        super().__init__("rate limited")
        self.seconds = seconds


