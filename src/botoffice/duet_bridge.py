@dataclass(frozen=True)
class DuetConfig:
    repo: str
    pr: int
    default_bot: str
    interval: int = DEFAULT_INTERVAL
    allowed_authors: tuple[str, ...] = ()
    enabled: bool = True
    senders: tuple[str, ...] = ()  # bots a job token may send as, besides default_bot

    @property
    def mailbox(self) -> str:
        return f"{self.repo.lower()}#{self.pr}"


def config_path(control_dir: Path) -> Path:
    return control_dir / CONFIG_NAME


def parse_config(data: Any) -> DuetConfig:
    if not isinstance(data, dict):
        raise DuetError("duet config must be a JSON object")
    repo = str(data.get("repo") or "").strip()
    if not _REPO.match(repo):
        raise DuetError("repo must look like owner/name")
    pr = data.get("pr")
    if isinstance(pr, bool) or not isinstance(pr, int) or pr < 1:
        raise DuetError("pr must be a positive integer")
    default_bot = str(data.get("default_bot") or "").strip()
    if not default_bot:
        raise DuetError("default_bot is required")
    interval = data.get("interval", DEFAULT_INTERVAL)
    if isinstance(interval, bool) or not isinstance(interval, (int, float)):
        raise DuetError("interval must be a number of seconds")
    interval = int(min(MAX_INTERVAL, max(MIN_INTERVAL, interval)))
    authors = data.get("allowed_authors") or []
    if not isinstance(authors, list) or not all(isinstance(a, str) and _LOGIN.match(a.strip()) for a in authors):
        raise DuetError("allowed_authors must be a list of GitHub logins")
    enabled = data.get("enabled", True)
    if not isinstance(enabled, bool):
        raise DuetError("enabled must be true or false")
    senders = data.get("senders") or []
    if not isinstance(senders, list) or not all(isinstance(s, str) and s.strip() and len(s) <= 200 for s in senders):
        raise DuetError("senders must be a list of bot names or ids")
    return DuetConfig(repo, pr, default_bot, interval, tuple(a.strip() for a in authors), enabled,
                      tuple(s.strip() for s in senders))


def _dir_state(directory: Path) -> tuple[int, ...] | None:
    """(mode, uid, ino, mtime) of the control directory, None when missing (lstat: a symlink is caught later)."""
    try:
        info = os.lstat(directory)
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise DuetError("duet config is unreadable", code="config_unreadable") from exc
    return (info.st_mode, info.st_uid, info.st_ino, info.st_mtime_ns)


def _read_private(path: Path) -> str | None:
    """The file's text, or None when it does not exist. The directory is opened and checked first (not a
    symlink, not group or world writable), then the file is opened relative to it with O_NOFOLLOW and
    O_NONBLOCK (a FIFO cannot block) and checked with fstat. Refused (DuetError): a symlink, not a regular
    file, group or world bits, another owner, or a directory others can write."""
    flags = getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    try:
        dfd = os.open(path.parent, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | flags)
    except FileNotFoundError:
        return None
    except OSError as exc:
        if path.parent.is_symlink():
            raise DuetError("the control directory must not be a symlink", code="config_dir_symlink") from exc
        raise DuetError("duet config is unreadable", code="config_unreadable") from exc
    try:
        directory = os.fstat(dfd)
        if directory.st_mode & 0o022:
            raise DuetError("the control directory is writable by others", code="config_dir_mode")
        try:
            fd = os.open(path.name, os.O_RDONLY | getattr(os, "O_NONBLOCK", 0) | flags, dir_fd=dfd)
        except FileNotFoundError:
            return None
        except OSError as exc:
            if path.is_symlink():
                raise DuetError("duet config must not be a symlink", code="config_symlink") from exc
            raise DuetError("duet config is unreadable", code="config_unreadable") from exc
    finally:
        os.close(dfd)
    with os.fdopen(fd, "rb") as stream:
        info = os.fstat(stream.fileno())
        if not stat_mod.S_ISREG(info.st_mode):
            raise DuetError("duet config must be a regular file", code="config_not_file")
        if info.st_mode & 0o077:
            raise DuetError("duet config is readable by others; run chmod 600 on it", code="config_mode")
        if hasattr(os, "geteuid") and info.st_uid != os.geteuid():
            raise DuetError("duet config is owned by another user", code="config_owner")
        try:
            return stream.read(1_000_000).decode("utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise DuetError("duet config is unreadable", code="config_unreadable") from exc


def load_config(control_dir: Path) -> DuetConfig | None:
    """None when there is no file. A symlink, loose permissions, another owner or bad JSON is refused."""
    text = _read_private(config_path(control_dir))
    if text is None:
        return None
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise DuetError("duet config is not JSON", code="config_json") from exc
    try:
        return parse_config(data)
    except DuetError as exc:
        exc.code = "config_invalid"
        raise


def install_config(raw: str, control_dir: Path) -> Path:
    text = raw.strip()
    if not text:
        raise DuetError("expected the mailbox JSON on stdin")
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise DuetError("stdin must be JSON") from exc
    config = parse_config(data)
    out = {"repo": config.repo, "pr": config.pr, "default_bot": config.default_bot, "interval": config.interval,
           "allowed_authors": list(config.allowed_authors), "enabled": config.enabled,
           "senders": list(config.senders)}
    path = config_path(control_dir)
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    if path.parent.is_symlink() or os.stat(path.parent).st_mode & 0o022:
        raise DuetError("the control directory is a symlink or writable by others")
    # an exclusive, randomly named temp file (O_EXCL, 0600) in the same directory, then an atomic rename
    fd, tmp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(json.dumps(out, indent=2) + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise
    return path


