HEADER_KEYS = ("id", "to", "thread", "kind", "reply_to")
# fixed codes for a to= the header could not say clearly (stored as the row's error until _drain reports it)
# a "not delivered" notice held back by a send limit waits for a later poll (NOTICE_WAIT, not charged); any
# other failure but a final one (NOTICE_FINAL) is tried again, up to NOTICE_ATTEMPTS times
NOTICE_WAIT = frozenset({"rate_attempts", "rate_bot", "rate_minute", "rate_day", "rate_limited",
                         "stopping"})  # not charged
# a notice refused for one of these never will be posted (its text, or its id's earlier outcome): final
NOTICE_FINAL = frozenset({"secret", "denylist", "send_unknown", "thread_cap", "reply_ambiguous",
                          "sender_not_allowed", "id_alloc"})
NOTICE_ATTEMPTS = 30
MAX_TARGET = 200
TARGET_HEADER_ERRORS = {"header_unclosed_quote": "a quote in the header was not closed",
                        "to_too_long": f"it is longer than {MAX_TARGET} characters",
                        "to_conflict": "it was given twice",
                        "to_empty": "it was empty", "to_trailing_text": "text followed the closing quote"}
# a known key at a word start: an unquoted value runs up to the next one (so "to=Test Bot kind=task" reads
# to="Test Bot"); a quoted value ("..." or curly double quotes) runs to its closing quote
_HEADER_KEY = re.compile(r"(?<!\S)(" + "|".join(HEADER_KEYS) + r")=", re.I)
# double quotes only: a single quote is an apostrophe as often as not (O'Neil), so it is a plain character
_QUOTES = {'"': '"', "\u201c": "\u201d"}
_CONTROL = re.compile(r"[\x00-\x1f\x7f-\x9f\u200b-\u200f\u2028-\u202e\u2060-\u206f\ufeff]")


def _norm_value(value: str) -> str:
    """A header value as text: control and invisible format characters dropped, runs of spaces collapsed."""
    return " ".join(_CONTROL.sub("", value).split())


class Inbound(NamedTuple):
    fields: dict[str, str]  # known header keys (lower case) with their values, spaces kept
    text: str
    problems: dict[str, str]  # key -> fixed code ("unclosed_quote", "conflict", "empty") for unusable fields


def parse_header(rest: str) -> tuple[dict[str, str], dict[str, str]]:
    """(fields, problems) for the header after the "[Duet -> Bot Office]" prefix. A value is quoted, or runs up
    to the next known key; unknown words before the first key are ignored. A key given twice with different
    values (compared exactly, after spacing), an unclosed quote or an empty value is a problem, never a guess."""
    fields: dict[str, str] = {}
    problems: dict[str, str] = {}
    marks = list(_HEADER_KEY.finditer(rest))
    pos = 0
    for index, mark in enumerate(marks):
        if mark.start() < pos:
            continue  # inside a quoted value
        key = mark.group(1).lower()
        start = mark.end()
        close = _QUOTES.get(rest[start:start + 1])
        if close:
            end = rest.find(close, start + 1)
            if end < 0:
                problems.setdefault(key, "unclosed_quote")
                break  # the rest of the line is the unclosed value: nothing after it is trusted
            value, pos = rest[start + 1:end], end + 1
            following = next((m for m in marks[index + 1:] if m.start() >= pos), None)
            if rest[pos:following.start() if following else len(rest)].strip():
                problems.setdefault(key, "trailing_text")  # to="Test" Bot: neither half is a safe reading
        else:
            following = next((m for m in marks[index + 1:] if m.start() > start), None)
            pos = following.start() if following else len(rest)
            value = rest[start:pos]
        value = _norm_value(value)
        if not value:
            problems.setdefault(key, "empty")
        elif key in fields and fields[key] != value:  # exact: two spellings may name two different bots
            problems[key] = "conflict"
        else:
            fields.setdefault(key, value)
    if rest.count('"') % 2 or rest.count("\u201c") != rest.count("\u201d"):
        problems.setdefault("header", "unclosed_quote")  # a quote somewhere that never closes: not readable
    for key in problems:
        fields.pop(key, None)
    return fields, problems


def parse_inbound(body: str) -> Inbound | None:
    """(header fields, text, header problems) for a Duet to Bot Office comment, else None."""
    lines = _FOOTER.sub("", (body or "").lstrip("\ufeff")).split("\n", 1)
    first = lines[0].rstrip("\r").strip()
    match = _INBOUND_PREFIX.match(first)
    if not match:
        return None
    fields, problems = parse_header(first[match.end():])
    return Inbound(fields, (lines[1] if len(lines) > 1 else "").strip()[:MAX_TEXT], problems)


@dataclass
class _Status:
    last_poll_at: str | None = None
    last_http_status: int | None = None
    polls: int = 0
    not_modified: int = 0
    last_error: str | None = None  # a fixed code, never exception text
    errors: int = 0
    waiting_for: str | None = None  # why the worker is idle: no_config, disabled, no_token


@dataclass
class DuetBridge:
    store: Any  # JobStore
    settings: Settings
    turns: Any = None  # Turns (post_message for an idle bot)
    # (bot, text, hook) -> True when attached to a running/queued turn; hook(db) runs in the steer's transaction
    steer: Callable[[Any, str, Callable[[Any], None]], bool] | None = None
    transport: Transport | None = None  # None: default_transport (looked up at call time)
    clock: Callable[[], datetime] = lambda: datetime.now(UTC)
    status: _Status = field(default_factory=_Status)

    def __post_init__(self) -> None:
        self._identities: dict[str, tuple[int, str]] = {}  # sha256(token)[:16] -> (id, login) of the token
        self._author_ids: dict[str, int] = {}  # allowed login -> resolved numeric id
        self._repo_ok: tuple[str, datetime] | None = None
        self._repo_seen = 0.0  # time.monotonic() of the GitHub answer behind _repo_ok
        self._ignored: set[int] = set()  # comment ids already logged as ignored
        self._cooldown_until = 0.0  # time.monotonic() before which no GitHub request is made
        self._recovered = False  # inbound rows left "delivering" by an earlier process were settled
        self._repo_failures = 0  # bumped by every failed repository check (a delivery batch stops on a change)
        self._gate = threading.RLock()  # failure publication vs the hand-over decision
        self._drain_error: str | None = None
        self._send_lock = threading.Lock()
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None
        self._cfg_cache: tuple[tuple[int, ...], DuetConfig | None] | None = None
        self._api = first_env("BOT_OFFICE_GITHUB_API") or GITHUB_API

    # -- plumbing --

    def _db(self):
        return closing(self.store._connect())

    def _iso(self, moment: datetime | None = None) -> str:
        return (moment or self.clock()).astimezone(UTC).isoformat()

    def _http(self, method: str, url: str, headers: dict[str, str], body: bytes | None,
              check: Callable[[], None] | None = None) -> tuple[int, dict[str, str], bytes]:
        """Every GitHub request goes through here: no request starts after stop, or during a cooldown that
        any earlier rate-limited answer set (shared by polls, lookups, sends and reactions). *check* (may
        raise) is the caller's own last check, run right before the request starts."""
        def ready() -> None:
            self._ready()
            if check is not None:
                check()
        transport = self.transport or default_transport
        if transport is _DEFAULT_TRANSPORT:  # checked again once a request slot is free
            self._ready()
            answer = transport(method, url, headers, body, deadline=time.monotonic() + HTTP_TIMEOUT, ready=ready)
        else:
            ready()
            answer = transport(method, url, headers, body)
        wait = self._rate_wait(answer[0], answer[1])
        if wait is not None:
            self._cooldown_until = max(self._cooldown_until, time.monotonic() + wait)
        return answer

    def _ready(self) -> None:
        self._check_stop()
        left = self._cooldown_until - time.monotonic()
        if left > 0:
            raise _RateLimited(left)

    def _check_stop(self) -> None:
        if self._stop.is_set():
            raise _Stopped()

    def config(self) -> DuetConfig | None:
        path = config_path(self.settings.control_dir)
        try:
            info = path.lstat()
            key = (info.st_mtime_ns, info.st_size, info.st_mode, info.st_ino, info.st_uid,
                   *(_dir_state(path.parent) or ()))  # a directory change (mode, owner) re-checks too
        except OSError:
            self._cfg_cache = None
            return None
        if self._cfg_cache and self._cfg_cache[0] == key:
            return self._cfg_cache[1]
        config = load_config(self.settings.control_dir)  # raises DuetError for a loose or bad file
        self._cfg_cache = (key, config)
        return config

    def _headers(self, token: str, extra: dict[str, str] | None = None) -> dict[str, str]:
        headers = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
                   "X-GitHub-Api-Version": "2022-11-28", "User-Agent": "bot-office-duet"}
        headers.update(extra or {})
        return headers

    def _token(self) -> str:
        token = rules.github_token(self.settings)
        if not token:
            raise DuetError("no usable GitHub token (control dir github-token, mode 600)", 503, "no_token")
        return token

    def _meta(self, key: str) -> str | None:
        return self.store.get_meta(key)

    def _get_json(self, url: str, token: str, what: str) -> Any:
        self._check_stop()
        status, headers, body = self._http("GET", url, self._headers(token), None)
        wait = self._rate_wait(status, headers)
        if wait is not None:
            raise _RateLimited(wait)
        if status != 200:
            raise DuetError(f"GitHub {what} answered HTTP {status}", 502, f"{what}_http_{status}")
        try:
            return json.loads(body or b"null")
        except ValueError as exc:
            raise DuetError(f"GitHub {what} answer was not JSON", 502, f"{what}_json") from exc

    # -- mailbox repository --

    def verify_repo(self, config: DuetConfig, token: str, fresh: bool = False) -> float:
        """time.monotonic() of the GitHub answer that showed the repository private (see _check_repo)."""
        try:
            return self._check_repo(config, token, fresh)
        except BaseException:
            with self._gate:
                self._repo_failures += 1  # any failure (network, cooldown, stop too): a running batch stops
            raise

    def _check_repo(self, config: DuetConfig, token: str, fresh: bool = False) -> float:
        """Fail closed (DuetError 503) unless the mailbox repository is private and has the numeric id it had
        when first seen. For polling and delivery a pass is cached for REPO_CHECK_SECONDS; *fresh* (every
        outbound write) always asks GitHub. A failure is never cached."""
        key = config.repo.lower()
        now = self.clock()
        if not fresh and self._repo_ok and self._repo_ok[0] == key \
                and now - self._repo_ok[1] < timedelta(seconds=REPO_CHECK_SECONDS):
            return self._repo_seen
        self._repo_ok = None
        try:
            data = self._get_json(f"{self._api}/repos/{config.repo}", token, "repo")
            answered = time.monotonic()  # before pinning, which may wait for the database
        except DuetError as exc:
            raise DuetError("mailbox repository check failed; nothing is sent or delivered", 503,
                            "repo_check_failed") from exc
        if not isinstance(data, dict):
            raise DuetError("mailbox repository check failed", 503, "repo_check_failed")
        if data.get("private") is not True:
            raise DuetError("the mailbox repository is not private; nothing is sent or delivered", 503,
                            "repo_not_private")
        repo_id = data.get("id")
        if isinstance(repo_id, bool) or not isinstance(repo_id, int):
            raise DuetError("mailbox repository check failed", 503, "repo_check_failed")
        if str(data.get("full_name") or "").lower() != key:
            raise DuetError("the mailbox repository answered with another name", 503, "repo_name_mismatch")
        if self._pin_repo(key, repo_id) != repo_id:
            raise DuetError("the mailbox repository id changed; nothing is sent or delivered", 503,
                            "repo_id_changed")
        self._repo_ok = (key, now)
        self._repo_seen = answered
        return answered

    def _pin_repo(self, key: str, repo_id: int) -> int:
        """The repository id pinned for *key*: set on first use, in one write transaction, so concurrent
        first checks (poller and a send) agree on one winner. An id in the older combined pin map is kept."""
        meta = f"duet_repo_id:{key}"
        with self._db() as db:
            db.execute("BEGIN IMMEDIATE")
            try:
                row = db.execute("SELECT value FROM meta WHERE key=?", (meta,)).fetchone()
                if row is None:
                    first = repo_id
                    legacy = db.execute("SELECT value FROM meta WHERE key='duet_repo_ids'").fetchone()
                    try:
                        older = json.loads(legacy["value"]).get(key) if legacy else None
                    except (ValueError, AttributeError):
                        older = None
                    if isinstance(older, int) and not isinstance(older, bool):
                        first = older
                    db.execute("INSERT INTO meta (key, value) VALUES (?,?)", (meta, str(first)))
                    pinned = first
                else:
                    try:
                        pinned = int(row["value"])
                    except (TypeError, ValueError):
                        pinned = -1  # unreadable pin: fail closed (never re-pinned silently)
                db.execute("COMMIT")
            except BaseException:
                db.execute("ROLLBACK")
                raise
        return pinned

    # -- who may write to Bot Office --

    def allowed_authors(self, config: DuetConfig, token: str) -> dict[int, str]:
        """Numeric GitHub account id -> lower-case login of the accounts whose comments are delivered: the
        configured logins (resolved once, then pinned in meta), else the token's own account."""
        if not config.allowed_authors:
            digest = hashlib.sha256(token.encode()).hexdigest()[:16]
            if digest not in self._identities:
                data = self._get_json(f"{self._api}/user", token, "user")
                uid, login = (data.get("id"), data.get("login")) if isinstance(data, dict) else (None, None)
                if isinstance(uid, bool) or not isinstance(uid, int) or not isinstance(login, str) or not login \
                        or data.get("type", "User") not in ACCOUNT_TYPES:
                    raise DuetError("GET /user returned no account", 502, "user_invalid")
                self._identities = {digest: (uid, login.lower())}  # a rotated token replaces the old identity
            uid, login = self._identities[digest]
            return {uid: login}
        try:
            pinned = json.loads(self._meta("duet_author_ids") or "{}")
        except ValueError:
            pinned = {}
        if not isinstance(pinned, dict):
            pinned = {}
        result: dict[int, str] = {}
        for login in sorted({a.lower() for a in config.allowed_authors}):
            uid = self._author_ids.get(login)
            if uid is None:
                data = self._get_json(f"{self._api}/users/{quote(login)}", token, "users")
                if not isinstance(data, dict):
                    continue
                found, kind = data.get("id"), data.get("type")
                if isinstance(found, bool) or not isinstance(found, int) or kind not in ACCOUNT_TYPES \
                        or str(data.get("login") or "").lower() != login:
                    log.warning("duet: allowed author %s did not resolve to a user account; ignored", login)
                    continue
                if login in pinned and pinned[login] != found:
                    log.warning("duet: allowed author %s now belongs to another account id; ignored", login)
                    continue
                if login not in pinned:
                    pinned[login] = found
                    self.store.set_meta("duet_author_ids", json.dumps(pinned, sort_keys=True))
                self._author_ids[login] = uid = found
            result[uid] = login
        return result

    # -- inbound --

    def _mkey(self, config: DuetConfig, name: str) -> str:
        return f"duet_{name}:{config.mailbox}"

    def poll_once(self) -> float | None:
        """One poll. Returns seconds to wait before the next one when the server asked for more than the
        interval (rate limit), else None. Raises OSError/DuetError on failure (the loop backs off). Without a
        usable config or token it returns quietly (no GitHub call, no error)."""
        config = self.config()
        if config is None or not config.enabled:
            self.status.waiting_for = "no_config" if config is None else "disabled"
            return None
        token = rules.github_token(self.settings)
        if not token:
            self.status.waiting_for = "no_token"
            return None
        self.status.waiting_for = None
        self.verify_repo(config, token)
        allowed = self.allowed_authors(config, token)
        failure: BaseException | None = None
        try:
            self._scan(config, token, allowed)
        except (DuetError, OSError, ValueError, _RateLimited) as exc:
            failure = exc  # already recorded messages are still delivered below
        self._drain_error = None
        self._drain(config, token, allowed)
        if failure is not None:
            raise failure
        self.status.last_error = self._drain_error  # a message held back by its checks shows its code
        return None

    def _scan(self, config: DuetConfig, token: str, allowed: dict[int, str]) -> None:
        cursor_key, floor_key, etag_key = (self._mkey(config, n) for n in ("cursor", "floor", "etag"))
        floor = self._meta(floor_key)
        if not floor:
            floor = _stamp(self.clock())
            self.store.set_meta(floor_key, floor)  # first start: never replay history
            self.store.set_meta(cursor_key, floor)
        cursor = self._meta(cursor_key) or floor
        cursor_at = _parse_stamp(cursor) or _parse_stamp(floor)
        floor_at = _parse_stamp(floor) or cursor_at
        # an overlapping window (comment ids dedupe), never before the first start
        since = _stamp(max(floor_at, cursor_at - timedelta(seconds=OVERLAP_SECONDS)))
        url = f"{self._api}/repos/{config.repo}/issues/{config.pr}/comments?per_page=100&since={quote(since, safe='')}"
        extra = {}
        try:
            saved = json.loads(self._meta(etag_key) or "{}")
        except ValueError:
            saved = {}
        # the page-one 304 shortcut only for a single-page scan: a later page can change while page one does not
        if isinstance(saved, dict) and saved.get("url") == url and saved.get("etag") and saved.get("pages") == 1:
            extra["If-None-Match"] = saved["etag"]
        self._check_stop()
        self.status.polls += 1
        self.status.last_poll_at = self._iso()
        status, headers, body = self._http("GET", url, self._headers(token, extra), None)
        self.status.last_http_status = status
        if status == 304:
            self.status.not_modified += 1
            return
        wait = self._rate_wait(status, headers)
        if wait is not None:
            raise _RateLimited(wait)
        if status != 200:
            raise DuetError(f"GitHub comments answered HTTP {status}", 502, f"comments_http_{status}")
        etag = headers.get("etag")
        newest = cursor
        pages = 0
        while True:
            try:
                comments = json.loads(body or b"[]")
            except ValueError as exc:
                raise DuetError("GitHub comments answer was not JSON", 502, "comments_json") from exc
            if not isinstance(comments, list):
                raise DuetError("GitHub comments answer was not a list", 502, "comments_shape")
            for comment in sorted((c for c in comments if isinstance(c, dict)), key=lambda c: c.get("id") or 0):
                self._check_stop()
                stamp = str(comment.get("updated_at") or "")
                if stamp > newest:
                    newest = stamp
                self._record_comment(config, token, allowed, comment, floor)
            pages += 1
            nxt = _next_link(headers.get("link"))
            if not nxt:
                break
            if pages >= MAX_PAGES:
                # incomplete: keep the cursor, so the next poll scans this window again (ids dedupe)
                self.store.delete_meta(etag_key)
                raise DuetError("comment scan hit the page limit; the cursor was kept", 502, "scan_incomplete")
            if not nxt.startswith(self._api + "/"):
                raise DuetError("refusing a pagination link outside the GitHub API", 502, "foreign_link")
            self._check_stop()
            status, headers, body = self._http("GET", nxt, self._headers(token), None)
            wait = self._rate_wait(status, headers)
            if wait is not None:
                raise _RateLimited(wait)
            if status != 200:
                raise DuetError(f"GitHub comments page answered HTTP {status}", 502, f"comments_http_{status}")
        # a complete scan: only now does the cursor move
        if newest != cursor and _parse_stamp(newest):
            self.store.set_meta(cursor_key, newest)
            self.store.delete_meta(etag_key)  # the URL changes with the cursor: the old etag no longer applies
        elif etag:
            self.store.set_meta(etag_key, json.dumps({"url": url, "etag": etag, "pages": pages}))

    @staticmethod
    def _rate_wait(status: int, headers: dict[str, str]) -> float | None:
        if status not in (403, 429):
            return None
        retry = headers.get("retry-after")
        if retry and retry.strip().isdigit():
            return min(MAX_RATE_WAIT, float(retry))
        if status == 429 or headers.get("x-ratelimit-remaining") == "0":
            reset = headers.get("x-ratelimit-reset")
            if reset and reset.strip().isdigit():
                return min(MAX_RATE_WAIT, max(1.0, float(reset) - datetime.now(UTC).timestamp()))
            return 60.0
        return None

    def _ignore(self, comment_id: int, reason: str) -> None:
        if comment_id not in self._ignored:
            self._ignored.add(comment_id)
            log.info("duet: ignored comment %s (%s)", comment_id, reason)  # never the content

    def _record_comment(self, config: DuetConfig, token: str, allowed: dict[int, str], comment: dict,
                        floor: str) -> None:
        """Record an acceptable inbound comment as pending (once per comment id). Delivery is _drain's job."""
        try:
            comment_id = int(comment["id"])
        except (KeyError, TypeError, ValueError):
            return
        if comment_id <= 0:
            return
        parsed = parse_inbound(str(comment.get("body") or ""))
        if parsed is None:
            return
        user = comment.get("user") if isinstance(comment.get("user"), dict) else {}
        uid, login, kind = user.get("id"), str(user.get("login") or "").lower(), user.get("type")
        if isinstance(uid, bool) or not isinstance(uid, int) or allowed.get(uid) != login or kind not in ACCOUNT_TYPES:
            self._ignore(comment_id, "author not allowed")
            return
        created, updated = str(comment.get("created_at") or ""), str(comment.get("updated_at") or "")
        if not created or updated != created:
            self._ignore(comment_id, "edited")  # only verifiably unedited comments are delivered
            return
        if created < floor:
            return  # older than the first start
        fields, problems = parsed.fields, parsed.problems
        msg_id = _clean(fields.get("id", "")) or f"GH-{comment_id}"
        reply_to = _clean(fields.get("reply_to", ""))
        kind_name = fields.get("kind", "fyi").lower()
        if kind_name not in IN_KINDS:
            kind_name = "fyi"
        # the target keeps its spaces (bot names have them); a to= the header cannot say clearly is recorded
        # with a fixed code, and _drain reports it as undeliverable instead of guessing a bot
        target = fields.get("to", "")
        if "unclosed_quote" in problems.values():
            header_error = "header_unclosed_quote"  # nothing after an unclosed quote can be read, to= neither
        elif "to" in problems:
            header_error = f"to_{problems['to']}"
        elif len(target) > MAX_TARGET:
            header_error, target = "to_too_long", ""  # never resolved by a prefix
        else:
            header_error = None
        with self._db() as db:
            db.execute("BEGIN IMMEDIATE")
            try:
                if db.execute("SELECT 1 FROM duet_messages WHERE comment_id=?", (comment_id,)).fetchone():
                    db.execute("COMMIT")
                    return  # already seen: recorded once only
                thread = self._thread_for(db, config.mailbox, fields.get("thread", ""), reply_to, msg_id)
                used = self._thread_used(db, config.mailbox, thread)
                state, error = ("pending", header_error) if used < THREAD_CAP else ("refused", "thread_cap")
                node_id = comment.get("node_id") if isinstance(comment.get("node_id"), str) else None
                # the text itself is not stored: delivery reads it again over GraphQL with its edit state
                db.execute(
                    "INSERT INTO duet_messages (comment_id,direction,msg_id,thread,kind,gh_created_at,seen_at,state,"
                    "target,error,mailbox,author_id,author_login,node_id) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (comment_id, "in", msg_id, thread, kind_name, created, self._iso(), state, target,
                     error, config.mailbox, uid, login, node_id))
                db.execute("COMMIT")
            except BaseException:
                db.execute("ROLLBACK")
                raise
        if state == "refused":
            log.info("duet: comment %s refused (thread cap)", comment_id)
            self._notice(config, token, thread=thread, reply_to=msg_id, cap_notice=True,
                         text=f"Message {msg_id} was not delivered: thread {thread} reached the cap of {THREAD_CAP} "
                              "messages. Start a new thread.")

    @staticmethod
    def _thread_for(db: Any, mailbox: str, raw: str, reply_to: str, own_id: str, *, strict: bool = False) -> str:
        """The canonical thread: the given one (safe characters only), else the thread of the message this
        replies to (in the same mailbox), else a new thread named after this message. Outbound ids are scoped
        to their sender, so a bare *reply_to* may match messages in several threads: it is never resolved to
        one of them. *strict* (sends) refuses it and asks for an explicit thread; inbound starts a new thread."""
        thread = _clean((raw or "").strip())
        if not thread and reply_to:
            found = [row["thread"] for row in db.execute(
                "SELECT DISTINCT thread FROM duet_messages WHERE msg_id=? AND mailbox=? AND thread!='' LIMIT 2",
                (reply_to, mailbox))]
            if len(found) == 1:
                thread = found[0]
            elif found and strict:
                raise DuetError(f"reply_to {reply_to} matches messages in more than one thread; give the thread "
                                "explicitly", 409, "reply_ambiguous")
        return thread or _clean(own_id)

    @staticmethod
    def _thread_used(db: Any, mailbox: str, thread: str) -> int:
        """Messages that count toward the thread cap: admitted inbound ones and counted outbound ones."""
        return int(db.execute(
            "SELECT COUNT(*) FROM duet_messages WHERE mailbox=? AND thread=? AND ((direction='in' AND "
            f"COALESCE(state,'')!='refused') OR (direction='out' AND (state IS NULL OR state IN {_COUNTED})))",
            (mailbox, thread)).fetchone()[0])

    def _receipt(self, db: Any, mailbox: str, comment_id: int, bot_id: str, mode: str, job_id: str | None) -> None:
        """Inside the hand-over's own transaction (the steer message's or the new turn's): the structured
        receipt keyed by (mailbox, comment id), and the row marked delivered."""
        stamp = self._iso()
        db.execute("INSERT OR IGNORE INTO duet_receipts (mailbox, comment_id, bot_id, mode, job_id, created_at) "
                   "VALUES (?,?,?,?,?,?)", (mailbox, comment_id, bot_id, mode, job_id, stamp))
        db.execute("UPDATE duet_messages SET state='delivered', mode=?, job_id=?, delivered_at=?, error=NULL "
                   "WHERE comment_id=?", (mode, job_id, stamp, comment_id))

    def _recover(self) -> None:
        """Rows left "delivering" by an earlier process: delivered when the hand-over's receipt exists (it was
        written in the same transaction as the steer message or the turn), else pending again: the hand-over
        never committed, so a retry cannot duplicate it."""
        with self._db() as db:
            stuck = db.execute("SELECT comment_id, mailbox FROM duet_messages WHERE direction='in' "
                               "AND state='delivering'").fetchall()
            for row in stuck:
                receipt = db.execute("SELECT mode, job_id FROM duet_receipts WHERE mailbox=? AND comment_id=?",
                                     (row["mailbox"], row["comment_id"])).fetchone()
                if receipt:
                    db.execute("UPDATE duet_messages SET state='delivered', mode=?, job_id=?, error=NULL "
                               "WHERE comment_id=?", (receipt["mode"], receipt["job_id"], row["comment_id"]))
                else:
                    db.execute("UPDATE duet_messages SET state='pending', error='recovered_pending' "
                               "WHERE comment_id=?", (row["comment_id"],))

    def verify_comment(self, token: str, row: Any) -> str:
        """The comment's current text from GraphQL, only when GitHub says it was never edited
        (lastEditedAt null, includesCreatedEdit false) and its author is the pinned account. Raises DuetError
        with a fixed code otherwise: "edited" and "comment_mismatch" are final, the others are retried."""
        node_id = row["node_id"]
        if not isinstance(node_id, str) or not node_id:
            raise DuetError("the comment has no node id", 502, "comment_mismatch")
        status, headers, answer = self._http("POST", f"{self._api}/graphql",
                                             self._headers(token, {"Content-Type": "application/json"}),
                                             json.dumps({"query": _GRAPHQL_COMMENT,
                                                         "variables": {"id": node_id}}).encode())
        wait = self._rate_wait(status, headers)
        if wait is not None:
            raise _RateLimited(wait)  # deferred (the cooldown is set): not a failed delivery attempt
        if status != 200:
            raise DuetError(f"GitHub GraphQL answered HTTP {status}", 502, "edit_check_failed")
        try:
            data = json.loads(answer or b"{}")
        except ValueError as exc:
            raise DuetError("GitHub GraphQL answer was not JSON", 502, "edit_check_failed") from exc
        if not isinstance(data, dict) or data.get("errors"):
            raise DuetError("GitHub GraphQL answered with errors", 502, "edit_check_failed")
        node = (data.get("data") or {}).get("node") if isinstance(data.get("data"), dict) else None
        if not isinstance(node, dict) or not {"lastEditedAt", "includesCreatedEdit", "body", "author",
                                              "databaseId"} <= set(node):
            raise DuetError("GitHub GraphQL answer is missing fields", 502, "edit_check_failed")
        if node["lastEditedAt"] is not None or node["includesCreatedEdit"] is not False:
            raise DuetError("the comment was edited", 409, "edited")
        author = node["author"] if isinstance(node["author"], dict) else {}
        if node["databaseId"] != row["comment_id"] or author.get("databaseId") != row["author_id"] \
                or str(author.get("login") or "").lower() != row["author_login"] or not isinstance(node["body"], str):
            raise DuetError("the comment does not match what was recorded", 409, "comment_mismatch")
        parsed = parse_inbound(node["body"])
        if parsed is None or (_clean(parsed.fields.get("id", "")) or f"GH-{row['comment_id']}") != row["msg_id"]:
            raise DuetError("the comment does not match what was recorded", 409, "comment_mismatch")
        return parsed.text

    def _drain(self, config: DuetConfig, token: str, allowed: dict[int, str]) -> None:
        """Deliver pending inbound messages in order. Each batch starts with a fresh repository check, and stops
        when any check (also a concurrent send's) found a problem since. Each message is checked over GraphQL
        (never edited, same author) and its text taken from there. A transient failure keeps it pending
        (MAX_ATTEMPTS). The hand-over carries a durable key, and a turn records delivery in its own enqueue
        transaction, so a restart can tell whether a "delivering" row was handed over (see _recover)."""
        if not self._recovered:
            self._recover()
            self._recovered = True
        with self._db() as db:
            rows = db.execute("SELECT comment_id, msg_id, thread, kind, target, attempts, author_id, author_login, "
                              "node_id, error, state FROM duet_messages WHERE direction='in' AND state IN "
                              "('pending','undeliverable') AND mailbox=? "
                              "ORDER BY comment_id", (config.mailbox,)).fetchall()
        if not rows:
            return
        notices_held = False  # a send limit held a notice back: the others wait for a later poll too
        with self._gate:
            generation = self._repo_failures
        self.verify_repo(config, token, fresh=True)
        for row in rows:
            self._check_stop()
            self._batch_still_valid(config, generation)
            allowed = self.allowed_authors(config, token)  # the current allowlist (resolved ids are cached)
            comment_id, msg_id, thread, target = row["comment_id"], row["msg_id"], row["thread"], row["target"] or ""
            if row["state"] == "undeliverable":
                if not notices_held:  # its notice was not posted yet: try again
                    notices_held = not self._report_undeliverable(config, token, row)
                continue
            if row["author_id"] is None or allowed.get(int(row["author_id"])) != row["author_login"]:
                self._finish(comment_id, state="failed", error="author_not_allowed")
                continue  # the author was removed from the allowlist since (or the row predates pinning)
            bot, code, _why = self.resolve_target(config, target, row["error"])
            if bot is None:
                # never a guess: an unknown, ambiguous or unclear to= is reported back, not sent to the default bot
                self._finish(comment_id, state="undeliverable", error=code, attempts=0)
                log.info("duet: comment %s undeliverable (%s)", comment_id, code)  # fixed code only, never header text
                if not notices_held:
                    notices_held = not self._report_undeliverable(config, token, {**dict(row), "error": code,
                                                                                  "attempts": 0})
                continue
            attempts = int(row["attempts"] or 0) + 1
            try:
                text = self.verify_comment(token, row)
            except DuetError as exc:
                final = exc.code in ("edited", "comment_mismatch") or attempts >= MAX_ATTEMPTS
                self._finish(comment_id, state="failed" if final else "pending", error=exc.code, attempts=attempts)
                self._drain_error = exc.code
                log.info("duet: comment %s not delivered (%s)", comment_id, exc.code)
                continue
            except _RateLimited:
                raise  # deferred: no request started, the attempt is not charged
            except OSError:
                final = attempts >= MAX_ATTEMPTS
                self._finish(comment_id, state="failed" if final else "pending", error="edit_check_failed",
                             attempts=attempts)
                self._drain_error = "edit_check_failed"
                continue
            prompt = self.wrap_inbound(msg_id, thread, row["kind"] or "fyi", text)
            with self._gate:  # no repository-check failure can be published between this check and the hand-over
                self._check_stop()
                self._batch_still_valid(config, generation)
                self._finish(comment_id, state="delivering", bot_id=str(bot.id))
                try:
                    self._deliver(bot, prompt, comment_id, config.mailbox)
                except Exception as exc:  # noqa: BLE001 - recorded, never raised: one bad message must not stall
                    log.warning("duet delivery of comment %s failed (%s), attempt %s", comment_id,
                                type(exc).__name__, attempts)
                    final = attempts >= MAX_ATTEMPTS
                    self._finish(comment_id, state="failed" if final else "pending",
                                 error="delivery_failed" if final else "delivery_retry", attempts=attempts)
                    continue
            try:
                self._check_stop()
                self.react(config, token, comment_id)
            except _Stopped:
                raise
            except Exception as exc:  # noqa: BLE001
                log.warning("duet reaction failed: %s", type(exc).__name__)

    def _report_undeliverable(self, config: DuetConfig, token: str, row: Any) -> bool:
        """Post the "not delivered" notice for an undeliverable row (state "undeliverable", error = its code),
        then mark it failed. A notice held back by a send limit stays due, is not charged an attempt, and is
        tried again on a later poll; any other failure but a final one is charged, up to NOTICE_ATTEMPTS. Its fixed id means a retry never posts it twice. It may pass the thread cap: the
        message it answers was admitted under the cap, and each admitted message gets at most this one notice.
        False when a send limit held it back (the caller stops trying more notices this poll)."""
        code, target, comment_id = row["error"], row["target"] or "", row["comment_id"]
        why = self.undeliverable_reason(config, code, target)
        msg_id = row["msg_id"]
        problem = self._notice(config, token, thread=row["thread"], reply_to=msg_id, msg_id=f"BO-ND-{comment_id}",
                               text=f"Message {msg_id} was not delivered (undeliverable): {why}", over_cap=True)
        if problem in NOTICE_WAIT:
            return False
        attempts = int(row["attempts"] or 0) + 1
        if problem and problem not in NOTICE_FINAL and attempts < NOTICE_ATTEMPTS:
            self._finish(comment_id, attempts=attempts)
            return True
        self._finish(comment_id, state="failed", attempts=attempts)
        if problem:
            log.warning("duet: comment %s undeliverable and its notice was not posted (%s)", comment_id, problem)
        return True

    def undeliverable_reason(self, config: DuetConfig, code: str, target: str) -> str:
        """The reason told to the sender for an undeliverable code (worked out again: the bots may differ now)."""
        how = 'Use the bot\'s id, or its exact name (quote a name with spaces: to="Test Bot"), or to=default.'
        shown = _display(target, 80)
        if code in TARGET_HEADER_ERRORS:
            return f"the to= field could not be read ({TARGET_HEADER_ERRORS[code]}). {how}"
        if code == "no_bot":
            return f"no to= was given and the default bot '{_display(config.default_bot, 80)}' was not found."
        if code == "ambiguous_bot":
            bots = self.store.match_bots(target)
            names = ", ".join(f"{_display(b.name, 60)} (id {b.id})" for b in bots[:5])
            return f"to='{shown}' matches more than one bot" + (f": {names}" if len(bots) > 1 else "") + \
                ". Use the bot's id."
        return f"to='{shown}' does not match any bot. {how}"

    def resolve_target(self, config: DuetConfig, target: str, header_error: str | None = None
                       ) -> tuple[Any, str, str]:
        """(bot, "", "") for an inbound to=, else (None, fixed code, reason for the sender). Only a missing to=
        or to=default means the default bot; anything else must name exactly one bot (id, name or alias)."""
        if header_error in TARGET_HEADER_ERRORS:
            code = header_error
        elif not target or target.casefold() == "default":
            bots = self.store.match_bots(config.default_bot)
            code = "" if len(bots) == 1 else "no_bot"
        else:
            bots = self.store.match_bots(target)
            code = "" if len(bots) == 1 else "unknown_bot" if not bots else "ambiguous_bot"
        if not code:
            return bots[0], "", ""
        return None, code, self.undeliverable_reason(config, code, target)

    def _batch_still_valid(self, config: DuetConfig, generation: int) -> None:
        """Stop the delivery batch when a repository check failed since it began, or the config changed."""
        if self._repo_failures != generation:
            raise DuetError("a repository check failed during delivery; the batch stopped", 503, "repo_check_failed")
        current = self.config()  # DuetError for a file that became unsafe
        if current != config:
            raise DuetError("the mailbox config changed during delivery; the batch stopped", 409, "config_changed")

    @staticmethod
    def wrap_inbound(msg_id: str, thread: str, kind: str, text: str) -> str:
        reply = f'desk duet send --reply-to {msg_id}' + (f" --thread {thread}" if thread else "") + ' --text "..."'
        head = f"[Message from {SENDER} via the Duet mailbox: id={msg_id}" + \
               (f" thread={thread}" if thread else "") + f" kind={kind}]"
        return "\n".join((head, rules.UNTRUSTED_RULE, rules.untrusted("claude-duet", text),
                          f"To reply: {reply}"))

    def _deliver(self, bot: Any, prompt: str, comment_id: int, mailbox: str) -> tuple[str, str | None]:
        """Hand over as a steer, else a new turn; either way the receipt is written in that same transaction."""
        if self.steer is not None and self.steer(
                bot, prompt, lambda db: self._receipt(db, mailbox, comment_id, str(bot.id), "steer", None)):
            return "steer", None
        if self.turns is None:
            raise DuetError("no turn queue", 503, "no_turns")
        _message, job = self.turns.post_message(
            bot, prompt, source="inbox", sender=SENDER,
            hook=lambda db, job: self._receipt(db, mailbox, comment_id, str(bot.id), "turn", str(job.id)))
        return "turn", str(job.id)

    def _finish(self, comment_id: int, **values: Any) -> None:
        if not values:
            return
        cols = ", ".join(f"{k}=?" for k in values)
        with self._db() as db:
            db.execute(f"UPDATE duet_messages SET {cols} WHERE comment_id=?", (*values.values(), comment_id))

    def react(self, config: DuetConfig, token: str, comment_id: int) -> None:
        url = f"{self._api}/repos/{config.repo}/issues/comments/{comment_id}/reactions"
        status, _, _ = self._http("POST", url, self._headers(token, {"Content-Type": "application/json"}),
                                  json.dumps({"content": "eyes"}).encode())
        if status not in (200, 201):
            raise DuetError(f"reaction answered HTTP {status}", 502, "reaction_failed")

    # -- outbound --

    def check_text(self, text: str, token: str | None = None) -> None:
        """Refuse a secret-looking or denylisted text, or one holding a known credential. Never echoes the
        value. An explicitly configured denylist (BO_PUSH_DENYLIST) that cannot be read refuses the send."""
        if any(pattern.search(text) for pattern in _SECRETS):
            raise DuetError("message refused: it looks like it contains a secret or token", code="secret")
        known = [token, getattr(self.settings, "token", None), rules.github_token(self.settings)]
        if any(isinstance(value, str) and value and value in text for value in known):
            raise DuetError("message refused: it contains a credential", code="secret")
        named = first_env("BO_PUSH_DENYLIST")
        path = Path(named or "~/.config/bot-office/push-denylist.txt").expanduser()
        try:
            literals = [line.strip().lower() for line in path.read_text(encoding="utf-8").splitlines()]
        except FileNotFoundError:
            if named:
                raise DuetError("message refused: the configured push denylist cannot be read", 503,
                                "denylist_unreadable") from None
            return
        except (OSError, UnicodeDecodeError):
            raise DuetError("message refused: the push denylist cannot be read", 503, "denylist_unreadable") from None
        lowered = text.lower()
        if any(item and not item.startswith("#") and item in lowered for item in literals):
            raise DuetError("message refused: it contains a value on the push denylist", code="denylist")

    def may_send(self, config: DuetConfig, bot: Any) -> bool:
        """A job token may send only as the default bot or a bot listed in the config's senders."""
        for ref in (config.default_bot, *config.senders):
            found = self.store.find_bot(ref)
            if found is not None and str(found.id) == str(bot.id):
                return True
        return False

    def send(self, *, text: str, bot: Any = None, via_job: bool = False, to: str = "main", kind: str = "fyi",
             thread: str | None = None, reply_to: str | None = None, msg_id: str | None = None,
             job_alive: Callable[[], bool] | None = None) -> dict[str, Any]:
        """Post one message. *bot* is the sending bot (None: the operator, "agentdesk"); *via_job* says a job
        token asked, which is allowed only for the bots the config permits. *msg_id* makes the send idempotent.
        *job_alive* (job tokens) is asked again under the send lock and right before the POST."""
        text = (text or "").strip()
        if not text:
            raise DuetError("text must not be empty")
        if len(text) > MAX_TEXT:
            raise DuetError(f"text is over {MAX_TEXT} characters")
        kind = (kind or "fyi").strip().lower()
        if kind not in OUT_KINDS or kind == "error":
            raise DuetError(f"kind must be one of {', '.join(k for k in OUT_KINDS if k != 'error')}")
        if msg_id is not None and not _MSG_ID.match(msg_id.strip()):
            raise DuetError("id must be 3 to 64 letters, digits or _.:-")
        self.check_text(text)
        config = self.config()
        if config is None or not config.enabled:
            raise DuetError("the Duet bridge is not configured or is disabled", 503, "not_configured")
        if via_job and (bot is None or not self.may_send(config, bot)):
            raise DuetError("this bot may not send to Duet (the mailbox config's default_bot and senders may)", 403,
                            "sender_not_allowed")
        sender = (str(bot.id), str(bot.name)) if bot is not None else ("agentdesk", "agentdesk")
        token = self._token()
        try:
            return self._send_limited(config, token, sender=sender, to=_clean((to or "").strip() or "main"),
                                      kind=kind, thread=thread or "", reply_to=_clean((reply_to or "").strip()),
                                      text=text, msg_id=msg_id.strip() if msg_id else None,
                                      authorize=lambda current: not via_job or (bot is not None
                                                                                and self.may_send(current, bot)),
                                      job_alive=job_alive)
        except _Stopped:
            raise DuetError("the Duet bridge is shutting down", 503, "stopping") from None
        except _RateLimited:
            raise DuetError("GitHub rate limit; try again later", 429, "rate_limited") from None

    def _notice(self, config: DuetConfig, token: str, *, thread: str, reply_to: str, text: str,
                cap_notice: bool = False, msg_id: str | None = None, over_cap: bool = False
                ) -> str | None:  # noqa: D417
        """The bridge's own error message, through the same checks and limits as any send (a thread-cap notice
        may pass the thread cap, once per thread). *msg_id* makes it idempotent. Never raises: None when it
        was posted (or was before, same *msg_id*), else the fixed code why not."""
        try:
            self._send_limited(config, token, sender=NOTICE_SENDER, to="main", kind="error", thread=thread,
                               reply_to=reply_to, text=text, msg_id=msg_id, cap_notice=cap_notice,
                               over_cap=over_cap)
        except (DuetError, OSError, _RateLimited, _Stopped) as exc:
            code = exc.code if isinstance(exc, DuetError) else \
                "stopping" if isinstance(exc, _Stopped) else "rate_limited" if isinstance(exc, _RateLimited) \
                else "network"
            log.warning("duet notice not sent (%s)", code)
            return code
        return None

    def _send_limited(self, config: DuetConfig, token: str, *, sender: tuple[str, str], to: str, kind: str,
                      thread: str, reply_to: str, text: str, msg_id: str | None, cap_notice: bool = False,
                      over_cap: bool = False, authorize: Callable[[DuetConfig], bool] | None = None,
                      job_alive: Callable[[], bool] | None = None) -> dict[str, Any]:
        with self._send_lock:
            # a send that waited for the lock is checked again against the config as it is now
            current = self.config()
            if current is None or not current.enabled:
                raise DuetError("the Duet bridge is not configured or is disabled", 503, "not_configured")
            if current.mailbox != config.mailbox:
                raise DuetError("the mailbox changed while this send waited; send it again", 409, "mailbox_changed")
            config = current
            if authorize is not None and not authorize(config):
                raise DuetError("this bot may not send to Duet (the mailbox config's default_bot and senders may)",
                                403, "sender_not_allowed")
            self._check_job(job_alive)
            # limits and the attempt charge come first: no GitHub request before them
            key, msg_id, thread, done = self._reserve(config.mailbox, sender[0], thread, reply_to, kind, msg_id,
                                                      cap_notice, over_cap)
            if done is not None:
                return done  # the same id was sent before: idempotent
            parts = [("id", msg_id), ("from", _clean(sender[0], 80)), ("from_name", _header_value(sender[1])),
                     ("to", to), ("thread", thread), ("reply_to", reply_to), ("kind", kind)]
            header = "[Bot Office → Duet] " + " ".join(f"{k}={v}" for k, v in parts if v)
            body = f"{header}\n\n{text}"
            mailbox = config.mailbox
            repo_checked = [0.0]

            def still_allowed() -> None:
                """Asked again once the request slot is held, right before the review is posted: the mailbox
                config, the sender's authorization and the sending job (a slot wait may be long), and the
                private-repository check is still recent (REPO_FRESH_SECONDS), so a wait cannot widen it."""
                now = self.config()
                if now is None or not now.enabled:
                    raise DuetError("the Duet bridge is not configured or is disabled", 503, "not_configured")
                if now.mailbox != mailbox:
                    raise DuetError("the mailbox changed while this send waited; send it again", 409,
                                    "mailbox_changed")
                if authorize is not None and not authorize(now):
                    raise DuetError("this bot may not send to Duet (the mailbox config's default_bot and senders "
                                    "may)", 403, "sender_not_allowed")
                self._check_job(job_alive)
                # last, after the checks above (they read files and the database and may wait)
                if time.monotonic() - repo_checked[0] > REPO_FRESH_SECONDS:
                    raise DuetError("the repository check is too old by the time a request slot was free; "
                                    "send it again", 503, "repo_check_stale")

            try:
                self.check_text(body, token)  # the final serialized review, header fields included
                repo_checked[0] = self.verify_repo(config, token, fresh=True)  # asked again right before the write
                still_allowed()
            except BaseException:
                self._settle(key, state="failed", error="refused_before_send")
                raise
            return self._post(config, token, key, msg_id, body, check=still_allowed)

    @staticmethod
    def _check_job(job_alive: Callable[[], bool] | None) -> None:
        if job_alive is not None and not job_alive():
            raise DuetError("the sending job is no longer running", 403, "job_not_running")

    def _reserve(self, mailbox: str, sender_id: str, thread: str, reply_to: str, kind: str, msg_id: str | None,
                 cap_notice: bool = False, over_cap: bool = False) -> tuple[int, str, str, dict[str, Any] | None]:
        """Check the limits and record the send as reserved, in one write transaction, before any HTTP call."""
        moment = self.clock()
        with self._db() as db:
            db.execute("BEGIN IMMEDIATE")
            try:
                if msg_id is not None:  # idempotency is scoped to (mailbox, sender, id)
                    row = db.execute("SELECT comment_id, state, review_id, url FROM duet_messages WHERE "
                                     "direction='out' AND mailbox=? AND bot_id=? AND msg_id=?",
                                     (mailbox, sender_id, msg_id)).fetchone()
                    if row is not None and row["state"] in ("sent", None):
                        db.execute("COMMIT")
                        return int(row["comment_id"]), msg_id, "", {"id": msg_id, "review_id": row["review_id"],
                                                                     "url": row["url"] or "", "duplicate": True}
                    if row is not None and row["state"] != "failed":
                        raise DuetError(f"an earlier send with id {msg_id} has an unknown outcome; it is not sent "
                                        "again", 409, "send_unknown")

                def attempts(since: datetime, bot: str | None = None) -> int:
                    sql = "SELECT COUNT(*) FROM duet_attempts WHERE ts>=?" + (" AND bot_id=?" if bot else "")
                    return int(db.execute(sql, (self._iso(since), *((bot,) if bot else ()))).fetchone()[0])
                if attempts(moment - timedelta(seconds=60), sender_id) >= ATTEMPTS_PER_BOT_MINUTE \
                        or attempts(moment - timedelta(seconds=60)) >= ATTEMPTS_PER_MINUTE \
                        or attempts(moment - timedelta(days=1)) >= ATTEMPTS_PER_DAY:
                    raise DuetError("slow down: too many send attempts (refused ones count too)", 429, "rate_attempts")

                def count(since: datetime, bot: str | None = None) -> int:
                    sql = f"SELECT COUNT(*) FROM duet_messages WHERE direction='out' AND seen_at>=? AND " \
                          f"(state IS NULL OR state IN {_COUNTED})"
                    args: list[Any] = [self._iso(since)]
                    if bot is not None:
                        sql += " AND bot_id=?"
                        args.append(bot)
                    return int(db.execute(sql, args).fetchone()[0])
                if count(moment - timedelta(seconds=PER_BOT_SECONDS), sender_id):
                    raise DuetError(f"slow down: one send per {PER_BOT_SECONDS} s per bot", 429, "rate_bot")
                if count(moment - timedelta(seconds=60)) >= PER_MINUTE:
                    raise DuetError(f"slow down: at most {PER_MINUTE} sends a minute", 429, "rate_minute")
                if count(moment - timedelta(days=1)) >= PER_DAY:
                    raise DuetError(f"daily limit of {PER_DAY} sends reached", 429, "rate_day")
                retry = None
                for _attempt in range(5):
                    own = msg_id or f"BO-{uuid.uuid4().hex[:8]}"
                    clash = db.execute("SELECT comment_id, state FROM duet_messages WHERE direction='out' AND "
                                       "mailbox=? AND bot_id=? AND msg_id=?", (mailbox, sender_id, own)).fetchone()
                    if clash is None:
                        break
                    if msg_id is not None:  # a failed earlier send with this id: reuse its row
                        retry = int(clash["comment_id"])
                        break
                else:
                    raise DuetError("could not allocate a message id", 500, "id_alloc")
                canonical = self._thread_for(db, mailbox, thread, reply_to, own, strict=True)
                if cap_notice:
                    if db.execute("SELECT 1 FROM duet_messages WHERE direction='out' AND mailbox=? AND thread=? "
                                  "AND target='cap_notice'", (mailbox, canonical)).fetchone():
                        raise DuetError("the thread-cap notice was already sent", 429, "thread_cap")
                elif not over_cap and self._thread_used(db, mailbox, canonical) >= THREAD_CAP:
                    raise DuetError(f"thread cap of {THREAD_CAP} messages reached; start a new thread", 429,
                                    "thread_cap")
                stamp = self._iso(moment)
                marker = "cap_notice" if cap_notice else None
                if retry is not None:
                    key = retry
                    db.execute("UPDATE duet_messages SET thread=?, kind=?, bot_id=?, seen_at=?, state='reserved', "
                               "error=NULL, target=? WHERE comment_id=?", (canonical, kind, sender_id, stamp, marker, key))
                else:
                    key = _OUT_KEY_BASE - secrets.randbits(52)  # a surrogate row key, never derived from the id
                    while db.execute("SELECT 1 FROM duet_messages WHERE comment_id=?", (key,)).fetchone():
                        key = _OUT_KEY_BASE - secrets.randbits(52)
                    db.execute("INSERT INTO duet_messages (comment_id,direction,msg_id,thread,kind,bot_id,seen_at,"
                               "state,target,mailbox) VALUES (?,?,?,?,?,?,?,?,?,?)",
                               (key, "out", own, canonical, kind, sender_id, stamp, "reserved", marker, mailbox))
                db.execute("INSERT INTO duet_attempts (ts, bot_id) VALUES (?,?)", (stamp, sender_id))
                db.execute("COMMIT")
            except BaseException:
                db.execute("ROLLBACK")
                raise
        return key, own, canonical, None

    def _settle(self, key: int, **values: Any) -> None:
        try:
            self._finish(key, **values)
        except Exception as exc:  # noqa: BLE001 - the reservation stays counted
            log.warning("duet: could not record a send outcome (%s)", type(exc).__name__)

    def _post(self, config: DuetConfig, token: str, key: int, msg_id: str, body: str,
              check: Callable[[], None] | None = None) -> dict[str, Any]:
        url = f"{self._api}/repos/{config.repo}/pulls/{config.pr}/reviews"
        try:
            status, _, answer = self._http("POST", url, self._headers(token, {"Content-Type": "application/json"}),
                                           json.dumps({"event": "COMMENT", "body": body}).encode(), check=check)
        except (_Stopped, _RateLimited, DuetError):
            self._settle(key, state="failed", error="not_started")  # the request never started
            raise
        except _NotStarted as exc:
            self._settle(key, state="failed", error="not_started")
            raise DuetError(f"GitHub is busy; message {msg_id} was not sent, send it again", 503,
                            "github_busy") from exc
        except OSError as exc:
            self._settle(key, state="unknown", error="send_no_answer")
            raise DuetError(f"GitHub did not answer; message {msg_id} may or may not be posted (it counts against "
                            "the limits)", 502, "send_no_answer") from exc
        if 400 <= status < 500:
            self._settle(key, state="failed", error=f"send_http_{status}")  # a definite refusal: not counted
            raise DuetError(f"GitHub refused the review (HTTP {status})", 502, f"send_http_{status}")
        if status not in (200, 201):
            self._settle(key, state="unknown", error=f"send_http_{status}")
            raise DuetError(f"GitHub answered HTTP {status}; message {msg_id} may or may not be posted", 502,
                            f"send_http_{status}")
        try:
            data = json.loads(answer or b"{}")
            review_id = int(data["id"])
        except (ValueError, KeyError, TypeError) as exc:
            self._settle(key, state="unknown", error="send_bad_answer")
            raise DuetError(f"GitHub's answer was unreadable; message {msg_id} was probably posted", 502,
                            "send_bad_answer") from exc
        stamp = self._iso()
        link = str(data.get("html_url") or "")
        self._settle(key, state="sent", review_id=review_id, gh_created_at=str(data.get("submitted_at") or stamp),
                     delivered_at=stamp, mode="review", error=None, url=link)
        return {"id": msg_id, "review_id": review_id, "url": link}

